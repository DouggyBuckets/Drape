import { renderRubric } from "../extraction/prompt.js";
import { LABEL_COLUMNS } from "./labels.js";

/** eval/LABELING.md, generated from the same rubric the model sees. */
export function renderLabelingGuide(): string {
  return `<!-- Generated by \`npm run labeling-guide\` from src/extraction/rubric.ts. Do not edit by hand. -->
# Labeling guide

Hand labels for \`npm run eval:extraction\`. The definitions below are the exact rubric
the model is given, so disagreements measure the model, not differing definitions.

## How to label

1. Put photos in \`images/\` (gitignored). One item per photo, plain background if possible.
2. Add one row per photo to \`eval/labels.csv\`:

   \`\`\`
   ${LABEL_COLUMNS.join(",")}
   navy-coat.jpg,outerwear,navy,4,5,fall;winter
   \`\`\`

   - \`file\` is the filename inside \`images/\`.
   - \`seasons\` are separated by \`;\`.
   - Lines starting with \`#\` are ignored.
3. Label from the photo and this rubric **before** looking at what the model says.
   Pick the closest level; don't leave blanks.

## Rubric

${renderRubric()}
`;
}
